const importFareData = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to DB');

    const exists = await RouteFare.countDocuments();
    if (exists > 0) {
      await RouteFare.deleteMany({});
      console.log('Cleared existing RouteFare data');
    }

    let totalImported = 0;

    for (const file of excelFiles) {
      console.log(`\n=== Processing: ${path.basename(file)} ===`);
      
      const workbook = XLSX.readFile(file);
      console.log(`Sheets: ${workbook.SheetNames.length}`);

      for (const sheetName of workbook.SheetNames) {
        if (String(sheetName).includes('সারসংক্ষেপ') || String(sheetName).includes('Summary')) continue;
        
        const sheet = workbook.Sheets[sheetName];
        const data = XLSX.utils.sheet_to_json(sheet, { header: 1 });
        
        if (data.length < 5) continue;

        const routeName = String(sheetName);
        const routeNumberMatch = routeName.match(/এ-[\d]+/);
        const routeNumber = routeNumberMatch ? routeNumberMatch[0] : routeName;

        let fareEntries = [];
        
        // Find the header row and data start
        let headerRowIdx = -1;
        let dataStartIdx = -1;
        
        // Try to find header row (contains stop names, has 'স্টেশন' or similar)
        for (let i = 3; i < 8; i++) {
          if (data[i] && data[i].length > 2 && (data[i][2] || String(data[i][0]).includes('স্টেশন'))) {
            headerRowIdx = i;
            break;
          }
        }
        
        // Find data start (first row with distance > 0)
        for (let i = headerRowIdx + 1; i < data.length; i++) {
          if (data[i] && data[i].length > 2 && parseNumber(data[i][1]) >= 0) {
            dataStartIdx = i;
            break;
          }
        }
        
        // Format 1: Data2 triangular matrix (found header and data)
        if (headerRowIdx >= 0 && dataStartIdx >= 0) {
          const headerRow = data[headerRowIdx];
          const destinations = [];
          for (let col = 2; col < headerRow.length; col++) {
            if (headerRow[col] && String(headerRow[col]).length > 0) {
              destinations.push(normalizeStopName(headerRow[col]));
            }
          }
          
          const origins = [];
          for (let row = dataStartIdx; row < data.length; row++) {
            if (data[row] && data[row][0] && !String(data[row][0]).includes('বিঃ দ্রঃ') && parseNumber(data[row][1]) > 0) {
              const stopName = normalizeStopName(data[row][0]);
              const dist = parseNumber(data[row][1]);
              if (stopName) {
                origins.push({ name: stopName, dist, row: data[row] });
              }
            }
          }
          
          // Create fare entries (triangular matrix - only forward fares)
          const uniqueFares = new Set();
          for (let origIdx = 0; origIdx < origins.length; origIdx++) {
            const origin = origins[origIdx];
            for (let destIdx = 0; destIdx < destinations.length; destIdx++) {
              const toStop = destinations[destIdx];
              // Skip self-to-self
              if (origin.name === toStop) continue;
              // Matrix is triangular - fare is at column destIdx + 2
              const fare = parseNumber(origin.row[destIdx + 2]);
              if (fare > 0 && origin.name && toStop) {
                const key = `${origin.name}|${toStop}`;
                if (uniqueFares.has(key)) continue;
                uniqueFares.add(key);
                fareEntries.push({
                  routeNumber,
                  routeName,
                  from: origin.name,
                  to: toStop,
                  distance: origin.dist,
                  fare,
                  vehicleType: 'ডিজেল চালিত বাস'
                });
              }
            }
          }
        }
        // Format 2: Dhaka triangular matrix
        else if (data[4] && data[4].length > 2) {
          const fromStops = [];
          for (let row = 4; row < data.length; row++) {
            if (data[row] && data[row][0] && !String(data[row][0]).includes('বিঃ দ্রঃ')) {
              fromStops.push({ stop: normalizeStopName(data[row][0]), dist: parseFloat(data[row][1]) || 0 });
            }
          }

          for (let rowIdx = 0; rowIdx < fromStops.length; rowIdx++) {
            const rowData = data[4 + rowIdx];
            if (!rowData) continue;
            
            for (let destIdx = 0; destIdx < fromStops.length; destIdx++) {
              const fare = parseFloat(rowData[destIdx + 2]) || 0;
              if (fare > 0) {
                fareEntries.push({
                  routeNumber,
                  routeName,
                  from: fromStops[rowIdx].stop,
                  to: fromStops[destIdx].stop,
                  distance: fromStops[destIdx].dist,
                  fare,
                  vehicleType: 'ডিজেল চালিত বাস'
                });
              }
            }
          }
        }

        if (fareEntries.length > 0) {
          await RouteFare.insertMany(fareEntries, { ordered: false });
          console.log(`  ${routeName}: ${fareEntries.length} fares imported`);
          totalImported += fareEntries.length;
        }
      }
    }

    console.log(`\n=== Total imported: ${totalImported} fare records ===`);
    process.exit();
  } catch (err) {
    console.error('Import error:', err);
    process.exit(1);
  }
};

importFareData();